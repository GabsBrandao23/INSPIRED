
/**
 * Enum that represents the possible defense types
 * a character can have during combat.
 */
public enum DefenseType {

    /** Indicates that the character has no defense prepared. */
    NONE,

    /** Indicates that the prepared defense protects against physical attacks. */
    ARMOR,

    /** Indicates that the prepared defense protects against magic attacks. */
    MAGIC_RESISTANCE
}
